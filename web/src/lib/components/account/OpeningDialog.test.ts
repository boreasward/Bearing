import { afterEach, expect, it, vi } from 'vitest'
import { act, fireEvent, render, screen, waitFor } from '@testing-library/svelte'
import OpeningDialog from './OpeningDialog.svelte'
import { accountFixture } from './fixtures'

afterEach(() => vi.unstubAllGlobals())
it('does not deliver a late opening callback after leaving the account route', async () => {
  let release!: (response: Response) => void
  vi.stubGlobal('fetch', vi.fn(() => new Promise(resolve => { release = resolve })))
  const onopened = vi.fn()
  const view = render(OpeningDialog, { open: true, account: accountFixture, onopened })
  await screen.findByRole('dialog')
  await fireEvent.input(screen.getByLabelText('期初现金'), { target: { value: '1000' } })
  await fireEvent.input(screen.getByLabelText('开账日'), { target: { value: '2026-10-29' } })
  await fireEvent.click(screen.getByRole('button', { name: '核对期初值' }))
  await fireEvent.click(screen.getByRole('button', { name: '期初值正确，继续' }))
  await fireEvent.click(screen.getByRole('button', { name: '确认开账' }))
  await waitFor(() => expect(release).toBeTypeOf('function'))
  view.unmount()
  await act(async () => { release(new Response(JSON.stringify({ account: accountFixture, trades: [] }))); await new Promise(resolve => setTimeout(resolve, 0)) })
  expect(onopened).not.toHaveBeenCalled()
})
it('blocks non-finite opening cash before asking for confirmation', async () => {
  const fetcher = vi.fn()
  vi.stubGlobal('fetch', fetcher)
  render(OpeningDialog, { open: true, account: { ...accountFixture, opened: false }, onopened: vi.fn() })
  await screen.findByRole('dialog')
  await fireEvent.input(screen.getByLabelText('期初现金'), { target: { value: 'Infinity' } })
  await fireEvent.input(screen.getByLabelText('开账日'), { target: { value: '2026-10-29' } })
  await fireEvent.click(screen.getByRole('button', { name: '核对期初值' }))
  expect(await screen.findByText('期初现金须大于 0 且为有限数值')).toBeInTheDocument()
  expect(fetcher).not.toHaveBeenCalled()
})
it('requires two explicit confirmations and sends in-kind positions without subtracting cash', async () => {
  const fetcher = vi.fn().mockResolvedValue(new Response(JSON.stringify({ account: accountFixture, trades: [] })))
  vi.stubGlobal('fetch', fetcher)
  const onopened = vi.fn()
  render(OpeningDialog, { open: true, account: { ...accountFixture, opened: false }, onopened })
  await screen.findByRole('dialog', { name: '真实账户开账' })
  await fireEvent.input(screen.getByLabelText('期初现金'), { target: { value: '1000.10' } })
  await fireEvent.input(screen.getByLabelText('开账日'), { target: { value: '2026-10-29' } })
  await fireEvent.click(screen.getByRole('button', { name: '添加期初持仓' }))
  await fireEvent.input(screen.getByLabelText('期初代码 1'), { target: { value: 'mu' } })
  await fireEvent.input(screen.getByLabelText('期初股数 1'), { target: { value: '2' } })
  await fireEvent.input(screen.getByLabelText('期初成本 1'), { target: { value: '100.10' } })
  await fireEvent.click(screen.getByRole('button', { name: '核对期初值' }))
  expect(fetcher).not.toHaveBeenCalled()
  expect(await screen.findByRole('dialog', { name: '确认期初值' })).toHaveTextContent('1000.10')
  await fireEvent.click(screen.getByRole('button', { name: '期初值正确，继续' }))
  expect(fetcher).not.toHaveBeenCalled()
  expect(await screen.findByRole('dialog', { name: '开账后不可修改' })).toHaveTextContent('不会扣减期初现金')
  await fireEvent.click(screen.getByRole('button', { name: '确认开账' }))
  await waitFor(() => expect(onopened).toHaveBeenCalledWith(accountFixture))
  const body = JSON.parse(fetcher.mock.calls[0][1].body)
  expect(body).toMatchObject({ opening_cash: '1000.10', opened_on: '2026-10-29', opening_positions: [{ ticker: 'MU', quantity: '2', cost_per_share: '100.10' }] })
})
